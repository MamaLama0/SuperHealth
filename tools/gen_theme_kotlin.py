#!/usr/bin/env python3
"""Generate the LocalHealth Compose colour tokens from Google Health resources.

Inputs:
  <res>       apktool-decoded res/ directory of the Google Health APK (gm3_sys_color_* tokens)
  <palettes>  JSON produced by extract_gh_palettes.py (ExtendedColorScheme light/dark)
Output: Kotlin source on stdout.

Usage: gen_theme_kotlin.py <res> <palettes.json> <lightKey> <darkKey> > GhColors.kt
"""
import json
import re
import sys

res, palettes_path, light_key, dark_key = sys.argv[1:5]

colors = dict(re.findall(r'<color name="([^"]+)">([^<]+)</color>', open(res + "/values/colors.xml").read()))


def resolve(name, depth=0):
    v = colors[name].strip()
    if v.startswith("@color/") and depth < 10:
        return resolve(v[7:], depth + 1)
    v = v.lstrip("#")
    if len(v) == 6:
        v = "ff" + v
    return v.upper()


M3_ROLES = [
    "primary", "on_primary", "primary_container", "on_primary_container", "inverse_primary",
    "secondary", "on_secondary", "secondary_container", "on_secondary_container",
    "tertiary", "on_tertiary", "tertiary_container", "on_tertiary_container",
    "background", "on_background", "surface", "on_surface", "surface_variant", "on_surface_variant",
    "inverse_surface", "inverse_on_surface", "error", "on_error", "error_container", "on_error_container",
    "outline", "outline_variant", "surface_bright", "surface_dim", "surface_container",
    "surface_container_high", "surface_container_highest", "surface_container_low",
    "surface_container_lowest",
]


def camel(s):
    p = s.split("_")
    return p[0] + "".join(x.title() for x in p[1:])


def m3_scheme(mode):
    fn = "lightColorScheme" if mode == "light" else "darkColorScheme"
    lines = ["internal val Gh%sColorScheme = %s(" % (mode.title(), fn)]
    for r in M3_ROLES:
        key = "gm3_sys_color_%s_%s" % (mode, r)
        if key in colors:
            lines.append("    %s = Color(0x%s)," % (camel(r), resolve(key)))
    lines.append(")")
    return "\n".join(lines)


pal = json.load(open(palettes_path))["instances"]
FAMILIES = ["blue", "blueMarine", "goldenrod", "green", "lilac", "magenta", "tangerine", "teal", "error"]
ROLES = ["color", "container", "containerVariant", "data", "dataBright", "fixed", "fixedDim", "variant",
         "onColor", "onContainer", "onFixed", "onFixedVariant", "onVariant"]


def hexval(v):
    return "0x" + v.lstrip("#")


def ext_scheme(name, inst):
    out = ["internal val %s = ExtendedColorScheme(" % name]
    for f in FAMILIES:
        fam = inst[f]
        args = ", ".join("Color(%s)" % hexval(fam[r]) for r in ROLES)
        out.append("    %s = ColorFamily(%s)," % (f, args))
    out.append(")")
    return "\n".join(out)


print("""// GENERATED by tools/gen_theme_kotlin.py from Google Health %s resources — do not edit.
package app.localhealth.ui.theme

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

%s

%s

%s

%s
""" % ("5.10.1", m3_scheme("light"), m3_scheme("dark"),
       ext_scheme("GhLightExtendedColors", pal[light_key]), ext_scheme("GhDarkExtendedColors", pal[dark_key])))
